import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { cpus, platform, release, tmpdir } from 'node:os';
import { join } from 'node:path';
import { checkExpectations, listScenarios, ROOT, runCli, runScenarioCli } from '../tests/lib/scenario.js';
import { createGame } from '../src/sim/game.js';
import { createBot } from '../src/sim/bot.js';
import { findBrowser, screenshot } from './screenshot.js';

const phase = process.argv[2] || 'phase-1';
const skipShots = process.argv.includes('--no-screens');
const OUT = join(ROOT, 'docs', 'proof', phase);
mkdirSync(OUT, { recursive: true });
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);
const md = [];
const line = (s = '') => md.push(s);
let allOk = true;

const commit = (() => {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
})();
const dirty = (() => {
  try {
    return execFileSync('git', ['status', '--porcelain'], { cwd: ROOT, encoding: 'utf8' }).trim().length > 0;
  } catch {
    return false;
  }
})();

line(`# Proof — ${phase}`);
line();
line(`Generated by \`npm run proof -- ${phase}\` (scripts/make-proof.js). Do not edit by hand; re-run to regenerate.`);
line();
line(`- Commit: \`${commit}\`${dirty ? ' (working tree had uncommitted changes when generated)' : ''}`);
line(`- Machine: ${platform()} ${release()}, ${cpus()[0]?.model || 'cpu'} x${cpus().length}, Node ${process.version}`);
line();

const testRun = spawnSync(process.execPath, ['--test'], { cwd: ROOT, encoding: 'utf8' });
writeFileSync(join(OUT, 'npm-test.txt'), testRun.stdout + testRun.stderr);
const summary = (testRun.stdout.match(/ℹ (tests|pass|fail) \d+/g) || []).join(', ');
allOk &&= testRun.status === 0;
line('## 1. Unit + contract + scenario tests');
line();
line(`\`node --test\` → exit ${testRun.status} (${summary}). Full log: [npm-test.txt](npm-test.txt)`);
line();

line('## 2. Headless scenarios (requirement → expectation → actual)');
line();
line('Each scenario file in `tests/scenarios/` is run through the real `headless_cmd` from `game.contract.json`. `sha` is the SHA-256 prefix of the full JSONL output so a re-run at this tag can be compared.');
line();
line('| Scenario | Requirement | Checks | Result | sha |');
line('|---|---|---|---|---|');
const details = [];
for (const s of listScenarios()) {
  const { text, lines } = runScenarioCli(s);
  const res = checkExpectations(lines, s.expect);
  const ok = res.every((r) => r.ok);
  allOk &&= ok;
  line(`| ${s.name} | ${s.requirement} | ${res.filter((r) => r.ok).length}/${res.length} | ${ok ? 'PASS' : '**FAIL**'} | \`${sha(text)}\` |`);
  details.push({ name: s.name, ok, sha: sha(text), checks: res.map((r) => ({ expect: r.expect, actual: r.got, ok: r.ok })), end: lines.at(-1) });
}
writeFileSync(join(OUT, 'scenarios.json'), JSON.stringify(details, null, 2));
line();
line('Expected vs actual for every check: [scenarios.json](scenarios.json)');
line();

line('## 3. Determinism');
line();
const d = mkdtempSync(join(tmpdir(), 'ddl-proof-'));
const writeImmortal = (night) => {
  const f = join(d, `immortal${night}.json`);
  writeFileSync(f, JSON.stringify({ player: { flames: 999, pos: night === 3 ? [0, 0, -30] : [0, 0, 0] } }));
  return f;
};
const det = [];
for (const [night, seed] of [[1, 1], [1, 42], [2, 2026], [3, 7]]) {
  const a = join(d, `a${night}-${seed}.jsonl`);
  const b = join(d, `b${night}-${seed}.jsonl`);
  runCli(['--seed', String(seed), '--night', String(night), '--ticks', '6000', '--out', a]);
  runCli(['--seed', String(seed), '--night', String(night), '--ticks', '6000', '--out', b]);
  const ha = sha(readFileSync(a, 'utf8'));
  const hb = sha(readFileSync(b, 'utf8'));
  det.push({ seed: `night ${night} / seed ${seed}`, ha, hb, same: ha === hb });
  allOk &&= ha === hb;
}
line('| Night / seed | Run A sha | Run B sha | Identical |');
line('|---|---|---|---|');
for (const r of det) line(`| ${r.seed} | \`${r.ha}\` | \`${r.hb}\` | ${r.same ? 'yes' : '**no**'} |`);
line();

line('## 4. Playthrough by autopilot bot (real simulation, standard numbers)');
line();
line('`src/sim/bot.js` uses only player inputs (move, interact, pulse, dash). Default random night, no scenario. It is an evidence tool, not an optimal player.');
line();
line('| Night | Seed | Result | Reason | Ticks | Score | Lanterns lit | Hits taken |');
line('|---|---|---|---|---|---|---|---|');
const tuning = JSON.parse(readFileSync(join(ROOT, 'game.contract.json'), 'utf8')).tuning;
const winsBy = {};
for (const night of [1, 2, 3]) {
  winsBy[night] = 0;
  for (let seed = 1; seed <= 10; seed++) {
    const g = createGame({ tuning, seed, night });
    const bot = createBot();
    let over = {};
    let hits = 0;
    while (g.state === 'playing') for (const e of g.step(bot(g))) {
      if (e.name === 'game_over') over = e.data;
      if (e.name === 'player_hit') hits++;
    }
    if (g.state === 'won') winsBy[night]++;
    line(`| ${night} | ${seed} | ${g.state} | ${over.reason} | ${g.tick} | ${g.score} | ${g.lanterns.filter((l) => l.lit).length}/${g.lanterns.length} | ${hits} |`);
  }
}
line();
line(`Bot wins: night 1 ${winsBy[1]}/10, night 2 ${winsBy[2]}/10, night 3 ${winsBy[3]}/10.`);
line();

line('## 4b. Performance: full night headless (21,600 ticks max)');
line();
line('| Night | Wall time (ms) | Limit |');
line('|---|---|---|');
for (const night of [1, 2, 3]) {
  const out = join(d, `perf${night}.jsonl`);
  const t0 = Date.now();
  runCli(['--seed', '5', '--night', String(night), '--ticks', '21600', '--out', out, '--scenario', writeImmortal(night)]);
  const ms = Date.now() - t0;
  allOk &&= ms < 30000;
  const end = JSON.parse(readFileSync(out, 'utf8').trim().split(String.fromCharCode(10)).at(-1));
  line(`| ${night} | ${ms} (ran ${end.ticks} ticks) | 30000 |`);
}
line();
line('Scenario used for timing keeps the player alive (flames 999) so the run lasts the whole night.');
line();

if (phase === 'phase-4') {
  line('## 4c. Soak test and benchmark (Ticket-04)');
  line();
  const contract = JSON.parse(readFileSync(join(ROOT, 'game.contract.json'), 'utf8'));
  const soakOut = join(OUT, 'soak.json');
  const [sc, ...sbase] = contract.soak_cmd.split(' ');
  const sr = spawnSync(sc, [...sbase, '--seed', '7', '--nights', '10', '--out', soakOut], { cwd: ROOT, encoding: 'utf8' });
  const soak = JSON.parse(readFileSync(soakOut, 'utf8'));
  const soakOk = sr.status === 0 && soak.crashes === 0 && soak.mem_end_mb <= 1.2 * soak.mem_start_mb;
  allOk &&= soakOk;
  line(`- Soak (\`${contract.soak_cmd} --seed 7 --nights 10\`): crashes ${soak.crashes}, results ${soak.results.join(', ')}, RSS ${soak.mem_start_mb} → ${soak.mem_end_mb} MB (×${soak.mem_ratio}, limit ×1.2), JS heap ${soak.heap_used_start_mb} → ${soak.heap_used_end_mb} MB, ${soak.duration_s} s → **${soakOk ? 'PASS' : 'FAIL'}**. File: [soak.json](soak.json)`);
  const benchFile = join(OUT, 'bench.json');
  if (existsSync(benchFile)) {
    const b = JSON.parse(readFileSync(benchFile, 'utf8'));
    const ok = b.avg_fps >= 60 && b.p1_low_fps >= 30 && b.load_ms <= 10000;
    line(`- Bench (\`${contract.bench_cmd} --seed 42 --duration 30\`, run separately with a real window: \`npm run bench\`): avg_fps ${b.avg_fps}, p1_low_fps ${b.p1_low_fps}, frame_ms_p95 ${b.frame_ms_p95}, frames ${b.frames}, load_ms ${b.load_ms} → **${ok ? 'PASS (on this machine)' : 'FAIL'}**. Renderer: ${b.renderer}. OS: ${b.os}. File: [bench.json](bench.json)`);
  } else {
    line('- Bench: bench.json not found in this folder. Run `node scripts/bench.js --seed 42 --duration 30 --out docs/proof/phase-4/bench.json` (needs a display + Chrome/Edge).');
  }
  line();
}

line('## 5. Screenshots (real browser, headless, WebGL via SwiftShader)');
line();
if (skipShots || !findBrowser()) {
  line('_Skipped (no Chrome/Edge found or --no-screens)._');
} else {
  const shots = phase === 'phase-1' ? [
    ['01-start.png', 'seed=1', 'Start screen'],
    ['02-playing.png', 'autostart=1&seed=1&warp=900&bot=1', 'Night 1 gameplay with HUD'],
  ] : phase === 'phase-4' ? [
    ['01-menu.png', 'seed=1', 'Main menu with Bảng xếp hạng; key hints follow the current key bindings; UI text >= 18 px'],
    ['02-settings.png', 'autostart=1&screen=settings', 'Settings: colorblind, reduced motion, large text (x1.25), remappable keys with "Khôi phục mặc định"'],
    ['03-big-text-settings.png', 'autostart=1&screen=settings&big=1', 'Large text option (x1.25)'],
    ['04-captions-shade.png', 'autostart=1&night=1&seed=3&warp=299&bot=1', 'Caption "Bóng Mực xuất hiện" + edge arrow toward the new shade (shades spawn at tick 300)'],
    ['05-bench-scene.png', 'bench=1&seed=42&duration=2', 'Bench scene: night 1, 200 wander shades, 100 motes, L1-L3 lit, camera orbit r=30 y=15'],
    ['06-leaderboard.png', 'autostart=1&screen=board', 'Leaderboard screen (from the local leaderboard file)'],
  ] : phase === 'phase-3' ? [
    ['01-intro-goal.png', 'autostart=1&night=1&screen=intro', 'Night intro now states the new goal: keep >= 3/5 lanterns lit until dawn (240 s)'],
    ['02-hud-capacity.png', 'autostart=1&night=1&seed=9&warp=4000&bot=1', 'HUD: carried / capacity (3/12 after one successful light), lanterns k/n with "cần 3 lúc bình minh"'],
    ['03-colorblind.png', 'autostart=1&night=1&seed=9&warp=4000&bot=1&cb=1', 'Colorblind palette: shade outline and eyes #00B3FF'],
    ['04-result-dawn.png', 'autostart=1&night=1&seed=9&warp=20000', 'Result after dawn_survived (bot, seed 9)'],
  ] : [
    ['01-menu.png', 'seed=1', 'Main menu (T3 chuỗi 3 Đêm)'],
    ['02-intro-night2.png', 'autostart=1&night=2&screen=intro', 'Night intro: island name + Ông Đăng line'],
    ['03-night1-hud.png', 'autostart=1&night=1&seed=2&warp=1500&bot=1', 'Night 1: full HUD (flames top-left, mm:ss top-center, lanterns k/n + score top-right, 10-cell mote bar, dash/pulse cooldowns, off-screen arrow), standard palette (shade body + violet outline, Mây white shirt + red scarf)'],
    ['04-night2-bridge.png', 'autostart=1&night=2&seed=1&pitch=1.1&dist=70&yaw=90', 'Night 2 map from above: two islands r=28, bamboo bridge, launch pads, charm on bridge'],
    ['05-night3.png', 'autostart=1&night=3&seed=1&pitch=1.2&dist=75', 'Night 3 map from above: tier 2 + bell tower, tier-1 half ring (z>0), ramps'],
    ['06-night3-wind.png', 'autostart=1&night=3&seed=1&warp=1700&bot=1', 'Night 3 wind warning (leaves + "Gió sắp nổi"), Bùa Gió (red, gold edge)'],
    ['07-pause.png', 'autostart=1&night=1&seed=1&warp=300&screen=pause', 'Pause menu: Tiếp tục / Chơi lại Đêm / Cài đặt / Về menu'],
    ['08-result-won.png', 'autostart=1&night=1&seed=1&warp=20000', 'Night result after a win (bot, seed 1) with next-night button'],
  ];

  mkdirSync(join(OUT, 'screens'), { recursive: true });
  for (const [file, query, what] of shots) {
    try {
      await screenshot({ query, out: join(OUT, 'screens', file), budgetMs: 5000 });
      line(`- **${what}** — \`/?${query}\``);
      line(`  ![${file}](screens/${file})`);
    } catch (e) {
      line(`- ${file}: failed (${e.message})`);
    }
  }
}
line();
line(`## Overall: ${allOk ? 'PASS' : 'FAIL'}`);
writeFileSync(join(OUT, 'README.md'), md.join('\n') + '\n');
console.log(`${allOk ? 'PASS' : 'FAIL'} — wrote ${join(OUT, 'README.md')}`);
process.exit(allOk ? 0 : 1);
