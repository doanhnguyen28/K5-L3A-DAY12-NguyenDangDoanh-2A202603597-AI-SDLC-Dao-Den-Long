import { execFileSync, spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { cpus, platform, release, tmpdir } from 'node:os';
import { join } from 'node:path';
import { checkExpectations, listScenarios, ROOT, runCli, runScenarioCli } from '../tests/lib/scenario.js';
import { createGame } from '../src/sim/game.js';
import { createBot } from '../src/sim/bot.js';
import { findBrowser, screenshot } from './screenshot.js';

const phase = process.argv[2] || 'phase-1';
const skipShots = process.argv.includes('--no-screens');
const OUT = join(ROOT, 'docs', 'proof', phase);
mkdirSync(OUT, { recursive: true });
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16);
const md = [];
const line = (s = '') => md.push(s);
let allOk = true;

const commit = (() => {
  try {
    return execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: ROOT, encoding: 'utf8' }).trim();
  } catch {
    return 'unknown';
  }
})();
const dirty = (() => {
  try {
    return execFileSync('git', ['status', '--porcelain'], { cwd: ROOT, encoding: 'utf8' }).trim().length > 0;
  } catch {
    return false;
  }
})();

line(`# Proof — ${phase}`);
line();
line(`Generated by \`npm run proof -- ${phase}\` (scripts/make-proof.js). Do not edit by hand; re-run to regenerate.`);
line();
line(`- Commit: \`${commit}\`${dirty ? ' (working tree had uncommitted changes when generated)' : ''}`);
line(`- Machine: ${platform()} ${release()}, ${cpus()[0]?.model || 'cpu'} x${cpus().length}, Node ${process.version}`);
line();

const testRun = spawnSync(process.execPath, ['--test'], { cwd: ROOT, encoding: 'utf8' });
writeFileSync(join(OUT, 'npm-test.txt'), testRun.stdout + testRun.stderr);
const summary = (testRun.stdout.match(/ℹ (tests|pass|fail) \d+/g) || []).join(', ');
allOk &&= testRun.status === 0;
line('## 1. Unit + contract + scenario tests');
line();
line(`\`node --test\` → exit ${testRun.status} (${summary}). Full log: [npm-test.txt](npm-test.txt)`);
line();

line('## 2. Headless scenarios (requirement → expectation → actual)');
line();
line('Each scenario file in `tests/scenarios/` is run through the real `headless_cmd` from `game.contract.json`. `sha` is the SHA-256 prefix of the full JSONL output so a re-run at this tag can be compared.');
line();
line('| Scenario | Requirement | Checks | Result | sha |');
line('|---|---|---|---|---|');
const details = [];
for (const s of listScenarios()) {
  const { text, lines } = runScenarioCli(s);
  const res = checkExpectations(lines, s.expect);
  const ok = res.every((r) => r.ok);
  allOk &&= ok;
  line(`| ${s.name} | ${s.requirement} | ${res.filter((r) => r.ok).length}/${res.length} | ${ok ? 'PASS' : '**FAIL**'} | \`${sha(text)}\` |`);
  details.push({ name: s.name, ok, sha: sha(text), checks: res.map((r) => ({ expect: r.expect, actual: r.got, ok: r.ok })), end: lines.at(-1) });
}
writeFileSync(join(OUT, 'scenarios.json'), JSON.stringify(details, null, 2));
line();
line('Expected vs actual for every check: [scenarios.json](scenarios.json)');
line();

line('## 3. Determinism');
line();
const d = mkdtempSync(join(tmpdir(), 'ddl-proof-'));
const det = [];
for (const seed of [1, 42, 2026]) {
  const a = join(d, `a${seed}.jsonl`);
  const b = join(d, `b${seed}.jsonl`);
  runCli(['--seed', String(seed), '--night', '1', '--ticks', '6000', '--out', a]);
  runCli(['--seed', String(seed), '--night', '1', '--ticks', '6000', '--out', b]);
  const ha = sha(readFileSync(a, 'utf8'));
  const hb = sha(readFileSync(b, 'utf8'));
  det.push({ seed, ha, hb, same: ha === hb });
  allOk &&= ha === hb;
}
line('| Seed | Run A sha | Run B sha | Identical |');
line('|---|---|---|---|');
for (const r of det) line(`| ${r.seed} | \`${r.ha}\` | \`${r.hb}\` | ${r.same ? 'yes' : '**no**'} |`);
line();

line('## 4. Night 1 is completable (autopilot bot through the real simulation)');
line();
line('`src/sim/bot.js` plays using only the same inputs a player has (move, interact, pulse). Default random night, no scenario.');
line();
line('| Seed | Result | Reason | Ticks | Score | Flames left |');
line('|---|---|---|---|---|---|');
const tuning = JSON.parse(readFileSync(join(ROOT, 'game.contract.json'), 'utf8')).tuning;
let wins = 0;
for (let seed = 1; seed <= 10; seed++) {
  const g = createGame({ tuning, seed });
  const bot = createBot();
  let over = {};
  while (g.state === 'playing') for (const e of g.step(bot(g))) if (e.name === 'game_over') over = e.data;
  if (g.state === 'won') wins++;
  line(`| ${seed} | ${g.state} | ${over.reason} | ${g.tick} | ${g.score} | ${g.player.flames} |`);
}
line();
line(`Bot won ${wins}/10. An idle player (no input) loses: see test "full default night with no input ends lost".`);
line();

line('## 5. Screenshots (real browser, headless, WebGL via SwiftShader)');
line();
if (skipShots || !findBrowser()) {
  line('_Skipped (no Chrome/Edge found or --no-screens)._');
} else {
  const shots = [
    ['01-start.png', 'seed=1', 'Start screen with story and controls'],
    ['02-playing.png', 'autostart=1&seed=1&warp=900&bot=1', 'Mây (nón lá + đèn nhỏ), đom đóm, Bóng Mực, HUD (lửa, đom đóm, đèn, thời gian, điểm, thanh tỏa sáng)'],
    ['03-lit-lanterns.png', 'autostart=1&seed=1&warp=2700&bot=1&yaw=200', 'Lit lantern glows amber with safe-radius ring; island brightens as lanterns are lit'],
    ['04-won.png', 'autostart=1&seed=1&warp=6000', 'Win screen after all 5 lanterns lit, dawn sky, replay button'],
  ];
  mkdirSync(join(OUT, 'screens'), { recursive: true });
  for (const [file, query, what] of shots) {
    try {
      await screenshot({ query, out: join(OUT, 'screens', file), budgetMs: 5000 });
      line(`- **${what}** — \`/?${query}\``);
      line(`  ![${file}](screens/${file})`);
    } catch (e) {
      line(`- ${file}: failed (${e.message})`);
    }
  }
}
line();
line(`## Overall: ${allOk ? 'PASS' : 'FAIL'}`);
writeFileSync(join(OUT, 'README.md'), md.join('\n') + '\n');
console.log(`${allOk ? 'PASS' : 'FAIL'} — wrote ${join(OUT, 'README.md')}`);
process.exit(allOk ? 0 : 1);
